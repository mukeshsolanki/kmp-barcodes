package com.mukeshsolanki.barcodes.internal.zxing.datamatrix.encoder

/** Forces square or rectangular Data Matrix symbols. */
internal enum class SymbolShapeHint {
    /** Any shape; the smallest fitting symbol wins. */
    FORCE_NONE,

    /** Square symbols only. */
    FORCE_SQUARE,

    /** Rectangular symbols only. */
    FORCE_RECTANGLE,
}
